export type AppLanguage = 'system' | 'uk' | 'ru';
export type ResolvedLanguage = 'uk' | 'ru';

export function deviceLanguage(): ResolvedLanguage {
  const locale = Intl.DateTimeFormat().resolvedOptions().locale.toLowerCase();
  return locale.startsWith('ru') ? 'ru' : 'uk';
}

export function resolveLanguage(choice: AppLanguage): ResolvedLanguage {
  return choice === 'system' ? deviceLanguage() : choice;
}

